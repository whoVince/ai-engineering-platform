package com.example.controller;

import com.example.entity.*;
import com.example.repository.*;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.List;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/api")
public class MvpWorkflowController {
    private final EngineeringProjectRepository projects;
    private final GenerationRunRepository runs;
    private final GeneratedArtifactRepository artifacts;
    private final ReviewDecisionRepository reviews;
    private final UsageEstimateRepository usage;

    public MvpWorkflowController(EngineeringProjectRepository projects, GenerationRunRepository runs,
            GeneratedArtifactRepository artifacts, ReviewDecisionRepository reviews, UsageEstimateRepository usage) {
        this.projects = projects; this.runs = runs; this.artifacts = artifacts; this.reviews = reviews; this.usage = usage;
    }

    @PostMapping("/projects/{projectId}/generations")
    @ResponseStatus(HttpStatus.CREATED)
    public GenerationResponse generate(@PathVariable Long projectId, @RequestBody @Valid GenerationRequest request) {
        EngineeringProject project = projects.findById(projectId).orElseThrow();
        GenerationRun run = runs.save(new GenerationRun(project.getId(), request.requirements()));
        List<GeneratedArtifact> generated = List.of(
            artifact(run, "README.md", "DOCUMENTATION", "# " + project.getName() + "\n\n" + request.requirements()),
            artifact(run, "docs/architecture.md", "ARCHITECTURE", "## Architecture\n\nGenerated by AI Engineering Platform Fake Provider."),
            artifact(run, "docs/api-contract.md", "API_CONTRACT", "## API contract\n\nPOST /api/projects/{id}/generations"),
            artifact(run, "database/schema.sql", "DATABASE_SCHEMA", "CREATE TABLE generated_artifact (...);")
        );
        generated.forEach(artifacts::save);
        run.complete("READY");
        runs.save(run);
        long input = request.requirements().length();
        long output = generated.stream().mapToLong(a -> a.getContent().length()).sum();
        usage.save(new UsageEstimate(run.getId(), input, output, BigDecimal.valueOf((input + output) * 0.000002), "USD"));
        return GenerationResponse.from(run, generated, null);
    }

    @GetMapping("/generations/{runId}")
    public GenerationResponse get(@PathVariable Long runId) {
        GenerationRun run = runs.findById(runId).orElseThrow();
        return GenerationResponse.from(run, artifacts.findByGenerationRunIdOrderByPath(runId),
            reviews.findFirstByGenerationRunIdOrderByDecidedAtDesc(runId).orElse(null));
    }

    @PostMapping("/generations/{runId}/review")
    public GenerationResponse review(@PathVariable Long runId, @RequestBody @Valid ReviewRequest request) {
        GenerationRun run = runs.findById(runId).orElseThrow();
        ReviewDecision decision = reviews.save(new ReviewDecision(runId, request.reviewer(), request.decision(), request.comment()));
        run.complete(request.decision().equals("APPROVED") ? "APPROVED" : "CHANGES_REQUESTED");
        runs.save(run);
        return GenerationResponse.from(run, artifacts.findByGenerationRunIdOrderByPath(runId), decision);
    }

    private GeneratedArtifact artifact(GenerationRun run, String path, String kind, String content) {
        return new GeneratedArtifact(run.getId(), path, kind, sha256(content), content);
    }

    private String sha256(String content) {
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256").digest(content.getBytes(StandardCharsets.UTF_8));
            return java.util.HexFormat.of().formatHex(digest);
        } catch (java.security.NoSuchAlgorithmException exception) {
            throw new IllegalStateException("SHA-256 is unavailable", exception);
        }
    }

    public record GenerationRequest(@NotBlank String requirements) {}
    public record ReviewRequest(@NotBlank String reviewer, @NotBlank String decision, String comment) {}
    public record GenerationResponse(Long id, String status, List<GeneratedArtifact> artifacts, ReviewDecision review) {
        static GenerationResponse from(GenerationRun run, List<GeneratedArtifact> artifacts, ReviewDecision review) {
            return new GenerationResponse(run.getId(), run.getStatus(), artifacts, review);
        }
    }
}

